function main() {
  // 사전 검증: newText에 한글/한자가 없는지 확인
  const KOREAN_RE = /[가-힣ᄀ-ᇿ㄰-㆏]/;
  const KANJI_RE  = /[一-龯㐀-䶿]/;
  let preCheckFailed = 0;
  PATCHES.forEach((p, i) => {
    if (KOREAN_RE.test(p.newText)) {
      console.error(`[${i+1}] 한글 잔존: ${p.file}\n  ${p.newText}`);
      preCheckFailed++;
    }
    if (KANJI_RE.test(p.newText)) {
      const matches = p.newText.match(new RegExp(KANJI_RE.source, 'g')) || [];
      console.error(`[${i+1}] 한자 발견: ${p.file} → ${matches.join('')}`);
      preCheckFailed++;
    }
  });
  if (preCheckFailed > 0) {
    console.error(`\n사전 검증 실패: ${preCheckFailed}건 — 패치 중단`);
    process.exit(1);
  }
  console.log(`사전 검증 통과 (${PATCHES.length}건 모두 한글/한자 없음)\n`);

  // 패치 적용
  let applied = 0, skipped = 0;
  for (const p of PATCHES) {
    if (!fs.existsSync(p.file)) {
      console.warn(`파일 없음: ${p.file}`);
      skipped++;
      continue;
    }
    const src = fs.readFileSync(p.file, 'utf8');
    if (!src.includes(p.oldText)) {
      console.warn(`매칭 실패 (이미 적용됨?): ${path.basename(p.file)}\n  찾는 텍스트 일부: ${p.oldText.slice(0, 40)}...`);
      skipped++;
      continue;
    }
    const occurrences = src.split(p.oldText).length - 1;
    if (occurrences > 1) {
      console.warn(`중복 매칭 (${occurrences}회): ${path.basename(p.file)} — 첫 번째만 교체`);
    }
    const newSrc = src.replace(p.oldText, p.newText);
    fs.writeFileSync(p.file, newSrc, 'utf8');
    applied++;
    console.log(`✓ ${path.basename(p.file)}: ${p.newText.slice(0, 30)}...`);
  }
  console.log(`\n완료 — 적용: ${applied} / 스킵: ${skipped} / 총: ${PATCHES.length}`);
}

main();
